import assert from 'node:assert/strict';
import vm from 'node:vm';
import { build } from 'esbuild';
import { JSDOM } from 'jsdom';

const output = await build({ entryPoints: ['src/features/share/inlineName.ts'], bundle: true, platform: 'node', format: 'cjs', external: ['obsidian'], write: false });
const notices = [];
const context = vm.createContext({ module: { exports: {} }, require: () => ({ Notice: class { constructor(message) { notices.push(message); } } }) });
vm.runInContext(output.outputFiles[0].text, context);
const { window } = new JSDOM('<div id="label">原名</div>');
const doc = window.document, label = doc.querySelector('#label');
window.HTMLElement.prototype.empty = function() { this.replaceChildren(); };
window.HTMLElement.prototype.setText = function(value) { this.textContent = value; };
window.HTMLElement.prototype.createEl = function(tag, options) {
  const element = doc.createElement(tag); element.className = options.cls;
  for (const [key, value] of Object.entries(options.attr)) element.setAttribute(key, value);
  this.append(element); return element;
};
const { editShareName } = context.module.exports;
const key = (input, value) => input.dispatchEvent(new window.KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true }));
let saves = [], cancels = 0;
let input = editShareName(label, '原名', async name => { saves.push(name); });
input.value = '新名'; key(input, 'Enter'); input.dispatchEvent(new window.Event('blur'));
await new Promise(resolve => setTimeout(resolve, 0));
assert.deepEqual(saves, ['新名'], 'Enter followed by blur saves once');
assert.equal(label.textContent, '新名');
input = editShareName(label, '新名', async name => saves.push(name), () => cancels++);
key(input, 'Escape'); input.dispatchEvent(new window.Event('blur'));
assert.equal(label.textContent, '新名'); assert.equal(cancels, 1); assert.equal(saves.length, 1);
input = editShareName(label, '新名', async name => saves.push(name));
input.value = '失焦确认'; input.dispatchEvent(new window.Event('blur'));
await new Promise(resolve => setTimeout(resolve, 0)); assert.equal(saves.at(-1), '失焦确认');
input = editShareName(label, '失焦确认', async () => { throw new Error('collision'); });
input.value = '冲突'; key(input, 'Enter');
await new Promise(resolve => setTimeout(resolve, 0));
assert(input.isConnected && !input.disabled, 'failed save leaves an editable name');
assert(notices.some(message => String(message).includes('collision')));
const errorsBeforeBlur = notices.length; input.dispatchEvent(new window.Event('blur'));
await new Promise(resolve => setTimeout(resolve, 0));
assert.equal(notices.length, errorsBeforeBlur, 'unchanged failed name does not retry on blur');
key(input, 'Escape');
console.log('Share inline names: Enter, blur, duplicate-save protection, Escape and failed-save recovery passed.');
