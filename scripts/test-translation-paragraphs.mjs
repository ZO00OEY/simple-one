import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {createRequire} from 'node:module';
const result=await build({entryPoints:['src/features/translationParagraphs.ts'],bundle:true,format:'cjs',platform:'node',write:false});
const module={exports:{}};new Function('require','module','exports',result.outputFiles[0].text)(createRequire(import.meta.url),module,module.exports);
const {paragraphTranslationRequest,interleaveTranslation}=module.exports;
assert.throws(()=>paragraphTranslationRequest('x'.repeat(12001),'translate'),/12000/);
assert.throws(()=>paragraphTranslationRequest('hello','x'.repeat(6001)),/6000/);
assert.throws(()=>paragraphTranslationRequest('hello','translate','x'.repeat(81),'英语'),/80/);
const boundary=paragraphTranslationRequest('"'.repeat(12000),'x'.repeat(6000));
assert(boundary.text.length>12000 && boundary.text.length<=128000,'raw text limit excludes JSON escaping');
assert(boundary.prompt.length>6000 && boundary.prompt.length<=8000,'user prompt limit excludes protocol instructions');
const shortParagraphs=paragraphTranslationRequest(('x\n\n').repeat(4000),'translate');
assert(shortParagraphs.text.length<=128000,'many short paragraphs fit the bounded JSON envelope');
const original='第一段 **原文**\n仍是第一段\n\nSecond paragraph.\n';
const request=paragraphTranslationRequest(original,'忠实翻译','中文','英语');
assert.equal(JSON.parse(request.text).length,2);assert(request.prompt.includes('中文 与 英语'));
assert.equal(interleaveTranslation(request.blocks,JSON.stringify([{id:2,translation:'第二段译文。'},{id:1,translation:'First translation.'}])),
 '第一段 **原文**\n仍是第一段\n\nFirst translation.\n\nSecond paragraph.\n\n第二段译文。\n','IDs determine placement while original words and Markdown remain unchanged');
for(const response of ['not json','[]','[{"id":1,"translation":"x"}]','[{"id":1,"translation":"x"},{"id":1,"translation":"y"}]','[{"id":1,"translation":"x"},{"id":3,"translation":"y"}]','[{"id":1,"translation":""},{"id":2,"translation":"y"}]']) assert.throws(()=>interleaveTranslation(request.blocks,response));
const code='Before.\n\n```js\nconst a=1;\n\nconst b=2;\n```\n\nAfter.';
const protectedRequest=paragraphTranslationRequest(code,'translate');
assert.equal(JSON.parse(protectedRequest.text).length,2,'fenced code is excluded from translation');
const output=interleaveTranslation(protectedRequest.blocks,'[{"id":1,"translation":"之前。"},{"id":2,"translation":"之后。"}]');
assert(output.includes('```js\nconst a=1;\n\nconst b=2;\n```'));
assert.throws(()=>paragraphTranslationRequest('```\ncode\n```','translate'));
const crlf=paragraphTranslationRequest('One.\r\n\r\nTwo.','translate');
assert.equal(interleaveTranslation(crlf.blocks,'[{"id":1,"translation":"一。"},{"id":2,"translation":"二。"}]'),'One.\r\n\r\n一。\r\n\r\nTwo.\r\n\r\n二。');
console.log('Paragraph translation: stable IDs, original preservation, code fences, CRLF and invalid responses passed.');
