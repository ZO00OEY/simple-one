import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { gzipSync } from "node:zlib";

export async function readerSource() {
  const filename = "src/features/share/reader/default.html";
  const html = (await fs.readFile(filename, "utf8")).replace(/\r\n/g, "\n");
  const script = /<script type="module" data-simple-reader>([\s\S]*?)<\/script>/.exec(html);
  const style = /<style data-simple-reader-style>([\s\S]*?)<\/style>/.exec(html);
  if (!script || !style) throw new Error("Default reader HTML is missing its script or style");
  return { html, script: script[1], style: style[1], filename };
}

export async function buildReaderFiles() {
  const source = await readerSource();
  const reader = await esbuild.build({
    stdin: { contents: source.script, resolveDir: path.resolve(path.dirname(source.filename)), sourcefile: "default.html.js", loader: "js" },
    bundle: true, write: false, outdir: "reader", format: "iife", minify: true, target: "es2020", metafile: true,
    loader: { ".woff2": "dataurl", ".woff": "dataurl", ".ttf": "dataurl" }, logLevel: "warning",
    plugins: [{ name: "modern-fonts", setup(build) {
      build.onLoad({ filter: /katex\.min\.css$/ }, async args => ({
        contents: (await fs.readFile(args.path, "utf8")).replace(/,url\([^)]*\.(?:woff|ttf)\) format\([^)]*\)/g, ""), loader: "css", resolveDir: path.dirname(args.path),
      }));
    } }],
  });
  const script = reader.outputFiles.find(file => file.path.endsWith(".js"))?.text;
  if (!script) throw new Error("Default reader script did not build");
  const css = source.style + "\n" + (reader.outputFiles.find(file => file.path.endsWith(".css"))?.text || "");
  // Store each large asset once; compose the standalone HTML after unpacking.
  const shell = source.html.replace(/<script type="module" data-simple-reader>[\s\S]*?<\/script>/, '<script data-simple-reader>__SIMPLE_READER_SCRIPT__</script>')
    .replace(/<style data-simple-reader-style>[\s\S]*?<\/style>/, '<style data-simple-reader-style>__SIMPLE_READER_STYLE__</style>');
  const files = { "reader/shell.html": shell, "reader/app.js": script, "reader/app.css": css };
  const packages = new Set(Object.keys(reader.metafile.inputs).map(input => /node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(input)?.[1]).filter(Boolean));
  const licenses = [];
  for (const name of [...packages].sort()) {
    const directory = `node_modules/${name}`;
    const filenames = (await fs.readdir(directory)).sort();
    const file = ["license", "license.md", "license.txt", "copying"].map(candidate => filenames.find(filename => filename.toLowerCase() === candidate)).find(Boolean);
    if (file) licenses.push(`\n=== ${name} ===\n${(await fs.readFile(`${directory}/${file}`, "utf8")).replace(/\r\n/g, "\n")}`);
  }
  files["reader/licenses.txt"] = licenses.join("\n");
  return { files, watchFiles: [source.filename, ...Object.keys(reader.metafile.inputs).filter(input => !input.endsWith("default.html.js"))].map(file => path.resolve(file)) };
}

export function standaloneReader(files) {
  return files["reader/shell.html"]
    .replace("__SIMPLE_READER_SCRIPT__", () => files["reader/app.js"].replace(/<\/script/gi, "<\\/script"))
    .replace("__SIMPLE_READER_STYLE__", () => files["reader/app.css"].replace(/<\/style/gi, "<\\/style"));
}

export async function writeDefaultReader() {
  const { files, watchFiles } = await buildReaderFiles();
  const template = standaloneReader(files);
  await fs.writeFile("default.html", template);
  await fs.writeFile("reader-licenses.txt", files["reader/licenses.txt"]);
  // Obsidian's installer downloads only the three standard plugin files.
  const payload = gzipSync(JSON.stringify({ template, licenses: files["reader/licenses.txt"] }), { level: 9 }).toString("base64");
  await fs.writeFile("src/features/share/readerPayload.ts", `// Generated by scripts/build-share-reader.mjs.\nexport const readerPayload = ${JSON.stringify(payload)};\n`);
  return watchFiles;
}
