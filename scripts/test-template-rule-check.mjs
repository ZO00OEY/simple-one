import assert from "node:assert/strict";
import { build } from "esbuild";
import { JSDOM } from "jsdom";
import { createRequire } from "node:module";
const output = await build({ entryPoints: ["src/features/templateRuleCheck.ts"], bundle: true, platform: "node", format: "cjs", write: false });
const module = { exports: {} };
new Function("require", "module", "exports", output.outputFiles[0].text)(createRequire(import.meta.url), module, module.exports);
const { checkTemplateSiteRule } = module.exports;
const doc = new JSDOM("").window.document;
const rule = { id: "test", urlPattern: "example\\.com", fields: [{ id: "field", fieldName: "Title", source: "h1", regex: "", replaceWith: "" }], search: { searchUrl: "https://example.com/?q={{queryEncoded}}", resultList: ".item", resultTitle: "a", resultUrl: "a", resultIntro: ".intro" } };
assert.ok(checkTemplateSiteRule(rule, doc).every(result => result.passed));
assert.ok(checkTemplateSiteRule(rule, doc).every(result => result.message.includes("未联网")));
assert.equal(checkTemplateSiteRule({ ...rule, urlPattern: "[" }, doc)[0].passed, false);
assert.equal(checkTemplateSiteRule({ ...rule, fields: [{ ...rule.fields[0], page: "missing" }] }, doc)[0].passed, false);
assert.equal(checkTemplateSiteRule({ ...rule, search: { ...rule.search, enabled: false } }, doc)[1].passed, false);
assert.equal(checkTemplateSiteRule({ ...rule, search: { ...rule.search, resultList: "[" } }, doc)[1].passed, false);
assert.equal(checkTemplateSiteRule({ ...rule, search: { ...rule.search, queryEncoding: "not-an-encoding" } }, doc)[1].passed, false);
assert.equal(checkTemplateSiteRule({ ...rule, fields: [{ ...rule.fields[0], source: "原始网址" }] }, doc)[0].passed, true);
console.log("Site rule checks: valid rules, regex/selectors, missing pages, disabled search, encoding and URL sources passed.");
