import assert from "node:assert/strict";
import vm from "node:vm";
import { build } from "esbuild";
const bundled = await build({ entryPoints: ["src/main.ts"], bundle: true, write: false, format: "cjs", platform: "browser", external: ["obsidian"] });
const context = vm.createContext({ module: { exports: {} }, require: () => new Proxy({}, { get: () => class {} }) });
vm.runInContext(bundled.outputFiles[0].text, context);
const plugin = Object.create(context.module.exports.default.prototype);
let sent;
plugin.settings = { sources: [{ id: "source", name: "Provider", models: [{ id: "translate", alias: "Translator" }] }], selected: { sourceId: "other", modelId: "chat" } };
plugin.cooperation = { request: async (...args) => { sent = args; return { text: "译文" }; } };
assert.equal(plugin.getTranslationModels()[0].label, "[Provider] Translator");
const input = { text: "hello", prompt: "Translate only.", sourceId: "source", modelId: "translate" };
assert.equal(await plugin.translateSelection(input), "译文");
assert.equal(sent[1].modelId, "translate"); assert.equal(sent[2], input.prompt);
assert.equal(sent[3].length, 1); assert.equal(sent[3][0].text, "hello"); assert.equal(sent[4].length, 0);
assert.equal(sent[6].maxOutputTokens, null); assert.equal(plugin.settings.selected.modelId, "chat");
const controller = new AbortController(), updates = [];
await plugin.translateSelection(input, controller.signal, text => updates.push(text));
sent[6].onUpdate({ text: 'incremental translation', reasoning: 'hidden reasoning' });
assert.deepEqual(updates, ['incremental translation']);
controller.abort(); sent[6].onUpdate({ text: 'late text', reasoning: '' });
assert.equal(updates.length, 1, 'aborted translation ignores late stream callbacks');
await plugin.translateSelection({ ...input, text: JSON.stringify([{id:1,text:'"'.repeat(12000)}]), prompt: 'x'.repeat(6300) });
assert.equal(sent[3][0].text.length,24020,'JSON framing is not mistaken for original source text');
await plugin.translateSelection({ ...input, text: 'x'.repeat(128001) });
await plugin.translateSelection({ ...input, prompt: 'x'.repeat(8001) });
await assert.rejects(plugin.translateSelection({ ...input, prompt: "" }), /提示词/);
assert.equal(plugin.getTranslationModels().length, 1, "available while the plugin is loaded without a master switch");
console.log("Translation bridge: model choice, isolated request, token cap and plugin-level availability passed; no paid calls.");
